"""Параметры кодирования: качество картинки, громкость, превью.

Один модуль на все виды вывода. Горизонталь, вертикаль и превью
отличаются размером кадра и фильтрами, но кодек, качество и уровень
громкости у них обязаны совпадать: клипы одного джоба не должны звучать
по-разному в зависимости от того, каким путём собрались.

## Почему CRF, а не битрейт

Битрейт задаёт вес файла, CRF — качество. На нашем материале правильное —
второе: клип на 15 секунд и клип на 90 секунд при одинаковом битрейте
получат разное качество, а при одинаковом CRF — одинаковое. Вес нас
не ограничивает; клип уедет на площадку, которая всё равно перекодирует
его под себя.

## Почему громкость приводится к −14 LUFS

EBU R128 — это про воспринимаемую громкость, а не про пики. Две сцены
из одного фильма легко расходятся на 6–8 LU: шёпот в диалоге и взрыв
сведены под кинозал, где на это есть динамический диапазон. В ленте
соцсети такой перепад означает, что один клип не слышно, а другой
бьёт по ушам.

−14 LUFS — уровень, к которому приводят звук YouTube и Spotify. Собранный
тише клип площадка не поднимет (она только приглушает), собранный громче —
прижмёт своим лимитером, и мы потеряем контроль над тем, как он звучит.

Нормализация однопроходная: двухпроходная точнее на десятые доли LU,
но требует прогнать весь файл дважды, а слышимой разницы на пятнадцати
секундах не даёт.
"""

from __future__ import annotations

from pathlib import Path
from typing import Final

from core.domain.render import RenderSpec

__all__ = [
    "LOUDNESS_RANGE",
    "TRUE_PEAK",
    "audio_args",
    "loudnorm_filter",
    "thumbnail_args",
    "video_args",
]

#: Потолок истинного пика, дБTP. −1.5 вместо нуля — запас на искажения,
#: которые вносит перекодирование на стороне площадки: сведённый впритык
#: к нулю звук после их AAC начинает клиппировать.
TRUE_PEAK: Final = -1.5

#: Целевой динамический диапазон, LU. 11 — рекомендация EBU для вещания:
#: сжимать сильнее значит выравнивать шёпот со взрывом, а это ровно та
#: выразительность, ради которой момент и выбран.
LOUDNESS_RANGE: Final = 11.0

#: Частота дискретизации на выходе. 48 кГц — стандарт видео; 44.1 кГц
#: из музыкальных исходников площадки всё равно пересчитают.
SAMPLE_RATE: Final = 48000

#: Пиксельный формат. yuv420p — единственный, который открывается везде,
#: включая старые телефоны и встроенные плееры соцсетей.
PIXEL_FORMAT: Final = "yuv420p"


def video_args(spec: RenderSpec, *, filter_chain: str | None = None) -> list[str]:
    """Аргументы видеопотока.

    ``filter_chain`` задаёт вызывающий, когда фильтры сложнее простого
    масштабирования (вертикальный кроп, блюр-фон). Если его нет, а размер
    в спецификации задан — собираем масштабирование сами.
    """
    args = [
        "-c:v",
        spec.video_codec,
        "-crf",
        str(spec.crf),
        "-preset",
        spec.preset,
        "-pix_fmt",
        PIXEL_FORMAT,
    ]

    chain = filter_chain or _scale_chain(spec)
    if chain:
        args += ["-vf", chain]
    if spec.threads:
        args += ["-threads", str(spec.threads)]
    return args


def audio_args(spec: RenderSpec) -> list[str]:
    """Аргументы звуковой дорожки.

    Принудительное стерео — не потеря: моно после апмикса звучит так же,
    а 5.1 из кинофайла в браузере без даунмикса превращается в тишину
    в центральном канале, то есть в пропавшие диалоги.
    """
    args = [
        "-c:a",
        spec.audio_codec,
        "-b:a",
        spec.audio_bitrate,
        "-ar",
        str(SAMPLE_RATE),
        "-ac",
        "2",
    ]
    if spec.loudness_lufs is not None:
        args += ["-af", loudnorm_filter(spec.loudness_lufs)]
    return args


def loudnorm_filter(target_lufs: float) -> str:
    return f"loudnorm=I={target_lufs:g}:TP={TRUE_PEAK:g}:LRA={LOUDNESS_RANGE:g}"


def thumbnail_args(source: Path, at_sec: float, width: int, destination: Path) -> list[str]:
    """Один кадр клипа в JPEG.

    Перемотка до `-i`: кадр берётся из уже нарезанного клипа, файл
    короткий, и точность здесь важнее скорости ровно настолько же,
    насколько в резке.
    """
    return [
        "-ss",
        f"{max(at_sec, 0.0):.3f}",
        "-i",
        str(source),
        "-frames:v",
        "1",
        "-vf",
        f"scale={width}:-2",
        # 2 по шкале mjpeg — визуально без артефактов; превью показывают
        # в ленте мелким, и платить за большее незачем.
        "-q:v",
        "2",
        "-y",
        str(destination),
    ]


def _scale_chain(spec: RenderSpec) -> str:
    if not spec.width and not spec.height:
        return ""
    # −2 вместо −1: размер округляется до чётного, а нечётная сторона
    # несовместима с yuv420p и роняет кодирование.
    width = spec.width or -2
    height = spec.height or -2
    return f"scale={width}:{height}"
