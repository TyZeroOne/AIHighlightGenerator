"""Вжигание субтитров в картинку.

Отдельный файл субтитров лучше вжжённого почти всегда: его можно
выключить, перевести, исправить опечатку. Поэтому по умолчанию
вжигание выключено (``BURN_SUBTITLES=false``).

Но есть случай, где оно обязательно: короткие вертикальные видео
смотрят без звука, и площадка либо не показывает загруженный SRT, либо
показывает своим шрифтом поверх нашей вёрстки. Там текст должен быть
частью изображения.

## Почему `ass`, а не `subtitles`

Фильтр `subtitles` умеет читать и SRT, и ASS, но для SRT ему приходится
выдумывать оформление — шрифт, кегль, положение, — и выдумывает он его
по умолчанию, одинаково для горизонтали и вертикали. Фильтр `ass` берёт
оформление из самого файла, где мы его уже посчитали под конкретный кадр.

## Где в цепочке фильтров

Строго последним. Вжечь до кропа значит вырезать половину текста вместе
с краями кадра; вжечь до масштабирования — получить текст, растянутый
вместе с картинкой. Текст нужно рисовать на том кадре, который увидит
зритель.
"""

from __future__ import annotations

from pathlib import Path

__all__ = ["append_burn", "ass_filter", "escape_filter_path"]


def ass_filter(path: Path) -> str:
    """Фильтр вжигания ASS-файла."""
    return f"ass='{escape_filter_path(path)}'"


def append_burn(chain: str, subtitles: Path | None) -> str:
    """Добавить вжигание в конец цепочки фильтров.

    Пустая цепочка и отсутствие субтитров — оба штатные случаи, поэтому
    функция работает как «прибавь, если есть что прибавлять», а не как
    обязательный шаг.
    """
    if subtitles is None:
        return chain
    return f"{chain},{ass_filter(subtitles)}" if chain else ass_filter(subtitles)


def escape_filter_path(path: Path) -> str:
    """Экранирование пути внутри аргумента фильтра.

    В графе фильтров двоеточие разделяет параметры, запятая — фильтры,
    а обратный слеш начинает escape-последовательность. Путь
    ``C:\\tmp\\a,b.ass`` разваливает разбор графа в трёх местах сразу,
    причём ffmpeg сообщает об этом как о «неизвестном фильтре».
    """
    text = str(path)
    for symbol in ("\\", ":", ",", "'", "[", "]", ";"):
        text = text.replace(symbol, "\\" + symbol)
    return text
