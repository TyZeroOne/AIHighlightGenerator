"""Промпты: инструкция ранжирования и инструкция для метаданных.

Отдельный модуль, а не строки внутри провайдера, по трём причинам.

**Кеширование.** Системная инструкция уходит в запрос с пометкой
`cache_control` и должна быть **байт в байт одинаковой** между вызовами:
кеш работает по префиксу, и любое различие обнуляет его целиком. Константа
в модуле — самый надёжный способ это гарантировать; f-строка, собранная
на месте, рано или поздно получит внутрь дату или `job_id`.

**Проверяемость.** Промпт — часть логики, и на него есть тесты: нет ли
внутри изменчивых подстановок, перечислены ли все категории из схемы.

**Читаемость diff-ов.** Правка формулировки видна отдельной строкой,
а не тонет в изменениях кода вокруг.

> **Чего в системном промпте не должно быть никогда**
>
> Текущей даты, `job_id`, UUID, названия конкретного видео — то есть всего,
> что меняется от запроса к запросу. Это классический «тихий инвалидатор»:
> ошибки не будет, кеш просто перестанет попадать, и счёт вырастет
> в несколько раз без единого признака в логах.
"""

from __future__ import annotations

from typing import Final

__all__ = ["METADATA_SYSTEM_PROMPT", "RANKING_SYSTEM_PROMPT"]

#: Инструкция ранжирования. Одинакова для всех видео и всех джобов —
#: это первая и самая стабильная точка кеширования.
RANKING_SYSTEM_PROMPT: Final = """\
Ты — редактор коротких видео. Тебе дают описания сцен из длинного видео, \
и нужно оценить, насколько каждая сцена годится в самостоятельный клип \
для соцсетей.

Что делает сцену хорошим клипом:
- в ней что-то происходит или что-то сообщается — она не «часть чего-то», \
а законченный момент;
- её можно понять без предыдущих сцен;
- в ней есть контраст с соседями: смена темпа, неожиданный поворот, \
резкая смена интонации;
- реплика или действие, которые хочется пересказать.

Что клипом не является:
- служебные планы, перебивки, титры, тишина;
- разговор, который непонятен без контекста;
- «красиво, но ничего не происходит».

Как оценивать:
- score — целое 0..100. Это не вероятность, а место в очереди: 90+ ставь \
только тому, что сам поставил бы первым; 50 — «сгодится, если не найдётся \
лучше»; ниже 30 — не публиковать.
- Сигналы и числа в описании — подсказки, а не приговор. Громкая сцена \
с быстрым монтажом может быть проходной перебивкой, а тихая пауза перед \
признанием — лучшим моментом видео. Смотри на смысл реплик.
- category выбирай по сути момента, а не по интонации описания.
- reason — одно предложение на языке видео: что именно здесь происходит \
и почему это сработает. Не пересказывай числа из описания.

Оценивай каждую присланную сцену ровно один раз. scene_index бери из \
заголовка сцены и не меняй: по нему результат сопоставляется с исходными \
данными. start и end копируй из заголовка без изменений.\
"""

#: Инструкция для метаданных клипа. Вторая независимая точка кеширования:
#: эти вызовы идут по одному на клип и разделяют общий префикс.
METADATA_SYSTEM_PROMPT: Final = """\
Ты — редактор соцсетей. По расшифровке короткого клипа нужно написать \
заголовок, описание и хештеги.

Правила:
- Пиши на языке речи в клипе. Если речи нет — на языке, указанном \
в контексте.
- Заголовок: до 100 символов, конкретный. Он должен сообщать, что \
в клипе, а не обещать, что «вы не поверите».
- Запрещены штампы: «шок», «вы не поверите», «это изменит вашу жизнь», \
«смотрите до конца», эмодзи-заборы, капс целыми словами.
- Описание: до 500 символов, 1–3 предложения. Можно добавить контекст, \
которого нет в самом клипе.
- Хештеги: от 3 до 10, без пробелов внутри, по теме клипа. \
Общие теги вроде #видео бесполезны — пиши те, по которым этот клип \
действительно стали бы искать.
- hook: одна фраза до 120 символов — то, что вынесут на обложку. \
Лучше всего работает прямая цитата из клипа.\
"""
