"""Запуск дочерних процессов, которые не переживают родителя.

Проблема, ради которой существует модуль, выглядит так. Воркер запускает
ffmpeg на сорок минут. Пользователь отменяет джоб, Celery убивает задачу —
и ffmpeg **продолжает работать**. В POSIX смерть родителя не убивает
детей: осиротевший процесс переходит к init и спокойно доедает ядра
до конца. Через десяток отмен на машине живут десять ffmpeg, о которых
никто не знает.

## Решение: PDEATHSIG

Linux умеет то, что нужно: ``prctl(PR_SET_PDEATHSIG, SIGKILL)`` просит
ядро прислать процессу сигнал, когда умрёт его родитель. Вызывается это
в самом дочернем процессе между ``fork`` и ``exec`` — то есть в
``preexec_fn``.

## Почему не «убить дерево процессов вручную»

Можно было бы запоминать pid'ы и обходить дерево при отмене. Это работает
ровно до первого случая, когда воркер убили не мы: SIGKILL по OOM,
падение контейнера, перезапуск ноды. PDEATHSIG отрабатывает и там,
потому что решение принимает ядро, а не наш код.

Платформа: только Linux. На Windows и macOS модуль отдаёт ``None``,
и процессы запускаются как обычно — там разработка, а не прод,
и осиротевший ffmpeg переживается одним ``taskkill``.
"""

from __future__ import annotations

import ctypes
import platform
from collections.abc import Callable
from typing import Final

__all__ = ["death_signal"]

#: Номер операции ``PR_SET_PDEATHSIG`` в ``prctl``. Константа из
#: ``linux/prctl.h``; в стандартной библиотеке Python её нет.
_PR_SET_PDEATHSIG: Final = 1

#: SIGKILL числом, а не ``signal.SIGKILL``: на Windows такого атрибута нет,
#: и проверка типов спотыкается о строку, которая там всё равно
#: не исполняется. Девятка одинакова во всех Linux-ABI.
_SIGKILL: Final = 9


def death_signal() -> Callable[[], None] | None:
    """``preexec_fn``, убивающий процесс вместе с родителем.

    ``None`` на неподдерживаемых платформах — вызывающий передаёт его
    в ``subprocess`` как есть, и поведение остаётся прежним.
    """
    if platform.system() != "Linux":
        return None

    def _set_pdeathsig() -> None:  # pragma: no cover — выполняется в дочернем процессе
        # Загружаем libc в ребёнке, а не в родителе: между fork и exec
        # безопасно только вызывать функции, не трогающие состояние
        # интерпретатора, и лишний импорт сюда тащить не стоит.
        libc = ctypes.CDLL("libc.so.6", use_errno=True)
        libc.prctl(_PR_SET_PDEATHSIG, _SIGKILL)

    return _set_pdeathsig
