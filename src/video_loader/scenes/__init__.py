"""Разбиение видео на сцены.

Две взаимозаменяемые реализации порта ``SceneDetector``:

* :mod:`video_loader.scenes.pyscenedetect` — основная, на PySceneDetect;
* :mod:`video_loader.scenes.ffmpeg` — фоллбек через фильтр ``scdet``.

Обе отдают **точки склеек**, а превращает их в сцены общий постпроцессор
(:mod:`video_loader.scenes.postprocess`): именно он отвечает за то, что сцены
покрывают окно целиком, не короче минимума и не длиннее максимума. Так
контракт порта выполняется одинаково обеими реализациями, а не «примерно
одинаково», как получилось бы, если бы каждая нормализовала результат сама.

Реэкспорта здесь намеренно нет. ``PySceneDetectDetector`` тянет за собой
OpenCV и NumPy — десятки мегабайт и заметные полсекунды импорта; если бы
пакет подтягивал их сам, то любое обращение к постпроцессору (чистые функции
над числами) грузило бы их заодно. Импортируйте нужный модуль напрямую.
"""

