"""Тональность текста и экспрессивность — без моделей.

Два признака из док 05, §5.1, которые считаются по буквам, а не сетью:
`speech.text.sentiment` и `speech.text.exclamations`.

> **Почему лексикон, а не модель**
>
> Соблазн взять готовый многоязычный классификатор тональности понятен,
> но он стоит ещё пятисот мегабайт весов и секунд на сцену — ради признака,
> который в скоринге весит немного и работает подсказкой, а не приговором.
> Лексикон даёт грубую, зато мгновенную и полностью офлайновую оценку.
>
> Ограничение честное и его надо знать: словарь короткий, сарказм
> и отрицание («не круто») он не понимает. Поэтому там, где не сработало
> ни одно слово, признак **не пишется вовсе** — «не знаю» полезнее нуля,
> который скоринг примет за нейтральность.

Сопоставление идёт по началу слова: для русского это дешёвая замена
лемматизации. Один префикс `любл` закрывает «люблю», «любленный»,
`ненавиж` — «ненавижу», «ненавижь». Отсюда и вид словаря.
"""

