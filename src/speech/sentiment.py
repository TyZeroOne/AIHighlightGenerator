#: Слова, из которых считается плотность: буквы и цифры, всё остальное —
#: разделители. Апостроф оставлен ради английских форм вроде «don't».
_WORD: Final = re.compile(r"[^\W_]+(?:'[^\W_]+)?", re.UNICODE)

#: Капсом считается слово из двух и более букв в верхнем регистре:
#: «Я» и «I» кричат не громче обычного, а вот «ВСЁ» — уже интонация.
_MIN_CAPS_LEN: Final = 2


def _matches(word: str, prefixes: tuple[str, ...]) -> bool:
    return any(word.startswith(prefix) for prefix in prefixes)


def text_sentiment(text: str) -> float | None:
    """Тональность текста в диапазоне −1..1 или ``None``, если не за что зацепиться.

    Нормировка идёт на число **сработавших** слов, а не на длину текста:
    иначе одна и та же реплика в длинной сцене выглядела бы нейтральнее,
    чем в короткой, хотя сказано ровно то же самое.
    """
    positive = 0
    negative = 0
    for match in _WORD.finditer(text.lower()):
        word = match.group()
        if _matches(word, POSITIVE):
            positive += 1
        elif _matches(word, NEGATIVE):
            negative += 1

    total = positive + negative
    if total == 0:
        return None
    return round((positive - negative) / total, 4)


def exclamation_density(text: str) -> float:
    """Плотность восклицаний, вопросов и капса на слово.

    Грубый, но на удивление живучий признак экспрессивности: спор, шутка
    и объявление отличаются от ровного повествования именно этим.
    """
    words = _WORD.findall(text)
    if not words:
        return 0.0

    marks = text.count("!") + text.count("?")
    caps = sum(
        1 for word in words if len(word) >= _MIN_CAPS_LEN and word.isupper() and word.isalpha()
    )
    return round(min((marks + caps) / len(words), 1.0), 4)
